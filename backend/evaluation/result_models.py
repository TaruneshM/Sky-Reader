from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ExecutionStatus(str, Enum):
    COMPLETED = "completed"
    FAILED = "failed"
    TIMEOUT = "timeout"
    SKIPPED = "skipped"


class FixtureMode(str, Enum):
    SYNTHETIC_FIXTURE = "synthetic_fixture"
    LIVE_DATA = "live_data"
    NONE = "none"


class EvaluationResult(BaseModel):
    """
    Structured record of a single benchmark execution for one system on one test case.
    Does NOT contain ground-truth answers or benchmark scores.
    """
    run_id: str = Field(..., description="Unique ID of the evaluation run session.")
    test_case_id: str = Field(..., description="Benchmark test case ID (e.g. 'TC-CUR-001').")
    system: str = Field(..., description="System identifier: 'baseline_llm', 'tool_using_agent', or 'sky_reader_full'.")
    category: str = Field(..., description="Benchmark category (e.g. 'current_weather').")
    question: str = Field(..., description="Natural language prompt presented to the system.")
    response: str = Field(default="", description="Text response generated by the system.")
    execution_status: ExecutionStatus = Field(default=ExecutionStatus.COMPLETED)
    error_type: Optional[str] = Field(default=None, description="Exception class or error classification if failed.")
    error_message: Optional[str] = Field(default=None, description="Error message details if failed.")
    model_identifier: str = Field(..., description="Underlying LLM model identifier (e.g. 'openai/gpt-oss-120b').")
    provider: str = Field(default="groq", description="LLM inference provider.")
    started_at: str = Field(..., description="ISO 8601 UTC timestamp when execution began.")
    completed_at: str = Field(..., description="ISO 8601 UTC timestamp when execution finished.")
    latency_ms: float = Field(default=0.0, description="Total wall-clock execution latency in milliseconds.")
    retry_count: int = Field(default=0, description="Number of retries attempted due to transient provider failures.")
    tool_calls: List[Dict[str, Any]] = Field(default_factory=list, description="List of tools invoked during reasoning.")
    fixture_id: Optional[str] = Field(default=None, description="Synthetic fixture ID injected, if applicable.")
    fixture_mode: FixtureMode = Field(default=FixtureMode.SYNTHETIC_FIXTURE)
    claims: Optional[List[Dict[str, Any]]] = Field(default=None, description="Claims extracted by Sky Reader, if applicable.")
    validation_report: Optional[Dict[str, Any]] = Field(default=None, description="Verification report if Sky Reader.")
    explanation: Optional[Dict[str, Any]] = Field(default=None, description="Explanation proof if Sky Reader.")
    risk_assessment: Optional[Dict[str, Any]] = Field(default=None, description="Risk assessment output if Sky Reader.")
    execution_metadata: Dict[str, Any] = Field(default_factory=dict, description="Diagnostic metadata (e.g. iterations).")


class RunSummary(BaseModel):
    """
    Metadata summary for a complete evaluation run session.
    """
    run_id: str
    started_at: str
    completed_at: str
    total_cases_selected: int
    total_executions: int
    completed_count: int
    failed_count: int
    timeout_count: int
    skipped_count: int
    systems_evaluated: List[str]
    categories_evaluated: List[str]
    config: Dict[str, Any] = Field(default_factory=dict)
